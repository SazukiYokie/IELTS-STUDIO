"""Generate the 'keep its own look' list for the light theme.
Light mode flips the whole page with a filter. Surfaces that are solid colour or originally light (bright buttons, gradient cards,
white cards) must be flipped back, and anything inside them must not be flipped a third time.
Run:  python3 tools/gen_light.py   (rewrites the marked block at the end of style.css; run it again whenever a new bright button or white card is added)"""
import re, colorsys, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSS = ROOT + '/style.css'
HTML = ROOT + '/index.html'
BEGIN, END = '/* LIGHT-KEEP:BEGIN (generated by gen_light.py, do not edit by hand) */', '/* LIGHT-KEEP:END */'

css = open(CSS).read()
if BEGIN in css:
    css = css[:css.index(BEGIN)].rstrip() + '\n' + css[css.index(END) + len(END):]
src = css

COLOR_RE = re.compile(r'#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|hsla?\([^)]*\)')


def parse_color(tok):
    tok = tok.strip()
    if tok.startswith('#'):
        h = tok[1:]
        if len(h) in (3, 4):
            h = ''.join(c * 2 for c in h)
        r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
        a = int(h[6:8], 16) / 255 if len(h) == 8 else 1.0
        return r / 255, g / 255, b / 255, a
    if tok.startswith('rgb'):
        nums = re.findall(r'[\d.]+%?', tok)
        v = [float(n[:-1]) / 100 * 255 if n.endswith('%') else float(n) for n in nums[:3]]
        a = float(nums[3]) if len(nums) > 3 else 1.0
        return v[0] / 255, v[1] / 255, v[2] / 255, a
    return None


def sat_light(c):
    r, g, b, a = c
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    chroma = max(r, g, b) - min(r, g, b)      # slate blues have a high HSL saturation but little chroma: they are neutral here
    return chroma, l, a


def qualifies(value):
    cols = [parse_color(m.group(0)) for m in COLOR_RE.finditer(value)]
    cols = [c for c in cols if c]
    if not cols:
        return False
    grad = 'gradient' in value
    for c in cols:
        s, l, a = sat_light(c)
        if a >= 0.85 and s >= 0.35 and 0.08 <= l <= 0.75:
            return True
    if not grad and len(cols) == 1:
        s, l, a = sat_light(cols[0])
        if a >= 0.9 and l >= 0.88:
            return True
    return False


def blocks(text, depth=0):
    """yield (selector, body) for every rule that has plain declarations, including inside @media/@supports"""
    i, n = 0, len(text)
    while i < n:
        j = text.find('{', i)
        if j < 0:
            break
        sel = text[i:j].strip()
        sel = re.sub(r'/\*.*?\*/', '', sel, flags=re.S).strip()
        k, d = j + 1, 1
        while k < n and d:
            if text[k] == '{':
                d += 1
            elif text[k] == '}':
                d -= 1
            k += 1
        body = text[j + 1:k - 1]
        if sel.startswith('@'):
            if re.match(r'@(media|supports)', sel) and 'print' not in sel:
                yield from blocks(body, depth + 1)
        else:
            yield sel, body
        i = k


keep = []
seen = set()
for sel, body in blocks(src):
    if '{' in body:
        continue
    if re.search(r'background-clip\s*:\s*text', body) or re.search(r'-webkit-background-clip\s*:\s*text', body):
        continue                      # gradient lettering must flip like text
    hit = False
    for m in re.finditer(r'(?<![\w-])background(?:-color|-image)?\s*:\s*([^;]+);?', body):
        if qualifies(m.group(1)):
            hit = True
            break
    if not hit:
        continue
    for one in sel.split(','):
        one = one.strip()
        if not one or one in seen or one in ('html', 'body', '*') or '::' in one or one.startswith('@') or re.match(r'\.(orb-\d|aurora-orb)', one):
            continue
        # skip the print sheet and the white report paper (handled by name below)
        seen.add(one)
        keep.append(one)

# tailwind classes in the page: bright solid backgrounds and white/very light surfaces
html = open(HTML).read()
toks = set(re.findall(r'(?<![\w/-])bg-([a-z]+)-([0-9]{2,3})(?![\w/])', html))
tw = []
HUES = {'red', 'orange', 'amber', 'yellow', 'lime', 'green', 'emerald', 'teal', 'cyan', 'sky', 'blue', 'indigo', 'violet', 'purple', 'fuchsia', 'pink', 'rose'}
for hue, n in sorted(toks):
    if hue in HUES and 400 <= int(n) <= 900:
        tw.append(f'[class~="bg-{hue}-{n}"]')
    if hue in ('slate', 'gray', 'zinc', 'neutral') and int(n) <= 200:
        tw.append(f'[class~="bg-{hue}-{n}"]')
if re.search(r'(?<![\w-])bg-white(?![\w/-])', html):
    tw.append('[class~="bg-white"]')
if 'bg-gradient-to-' in html:
    tw.append('[class*="bg-gradient-to-"]:not([class*="bg-clip-text"])')

# native controls are drawn by the browser (white boxes, accent ticks), so they are flipped back as well
native = ['input[type="checkbox"]', 'input[type="radio"]', 'input[type="range"]', 'progress', 'meter']
items = keep + tw + native
# bare element selectors and the print report paper are not part of this
items = [x for x in items if x not in ('html', 'body')]
lst = ',\n'.join('    ' + x for x in items)
inner = ',\n'.join('    ' + x for x in items)

out = f'''
{BEGIN}
/* flipped back: colour surfaces (buttons, gradient cards, selected chips) and originally light surfaces (white cards, the report paper) */
html[data-theme="light"] :is(
{lst}
) {{ filter: invert(1) hue-rotate(180deg); }}
/* ...and nothing inside them is flipped a second time */
html[data-theme="light"] :is(
{inner}
) :is(
{inner}
) {{ filter: none; }}
html[data-theme="light"] :is(
{inner}
) :is(img, video, canvas, picture, iframe) {{ filter: none; }}
{END}
'''
open(CSS, 'w').write(css.rstrip() + '\n' + out)
print('keep selectors:', len(keep), 'tailwind:', len(tw))
